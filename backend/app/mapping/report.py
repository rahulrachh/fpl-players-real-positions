"""Coverage report for the player ID mapping: `docs/mapping-coverage.md`,
written by `python -m app.mapping run` and by the sync CLI."""

from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.db.models import FplPlayer, PlayerIdMap, PlayerMatchPosition, SofascorePlayer
from app.mapping.overrides import OVERRIDES_PATH
from app.mapping.players import LOW_CONFIDENCE, MappingResult

REPORT_PATH = Path(__file__).resolve().parents[3] / "docs" / "mapping-coverage.md"


@dataclass(frozen=True)
class Coverage:
    players: int
    matched: int
    active: int
    active_matched: int

    @property
    def matched_pct(self) -> float:
        return _pct(self.matched, self.players)

    @property
    def active_pct(self) -> float:
        return _pct(self.active_matched, self.active)


def coverage(session: Session) -> Coverage:
    """Share of FPL players with a `player_id_map` row, of all players and of
    active ones (FPL minutes this season > 0)."""
    mapped = set(session.scalars(select(PlayerIdMap.fpl_id)))
    players = session.scalars(select(FplPlayer)).all()
    active = [p for p in players if p.minutes > 0]
    return Coverage(
        players=len(players),
        matched=sum(p.id in mapped for p in players),
        active=len(active),
        active_matched=sum(p.id in mapped for p in active),
    )


def render_report(session: Session, result: MappingResult, generated_at: datetime) -> str:
    cov = coverage(session)
    players = {p.id: p for p in session.scalars(select(FplPlayer))}
    rows = session.scalars(select(PlayerIdMap)).all()
    sofa = {p.id: p for p in session.scalars(select(SofascorePlayer))}

    out = [
        "# Player mapping coverage",
        "",
        "**Tasks:** 08, 09 · Code: `backend/app/mapping/` · Generated by "
        "`uv run python -m app.mapping run` (also by the sync) on "
        f"{generated_at:%Y-%m-%d %H:%M} UTC. Do not edit by hand.",
        "",
        "Active = FPL minutes this season > 0.",
        "",
        *OVERRIDE_FORMAT,
        "",
        "## Coverage",
        "| | Players | Mapped | % |",
        "|---|---|---|---|",
        f"| All FPL players | {cov.players} | {cov.matched} | {cov.matched_pct:.1f}% |",
        f"| Active players | {cov.active} | {cov.active_matched} | {cov.active_pct:.1f}% |",
        "",
        "| Method | Rows |",
        "|---|---|",
    ]
    by_method = result.by_method
    for method in ("exact", "short_name", "surname_initial", "fuzzy"):
        out.append(f"| `{method}` | {by_method.get(method, 0)} |")
    out += [f"| `override` | {len(result.overrides_applied)} |", ""]

    out += _overrides_section(result, players, sofa)

    out += ["## Clashes", ""]
    if result.clashes:
        out += [
            "Two FPL players claimed one Sofascore player; neither was mapped. Fix with an override.",
            "",
            "| Sofascore player | FPL players |",
            "|---|---|",
        ]
        for sofa_id, fpl_ids in result.clashes:
            claimants = "; ".join(_fpl_label(players[i]) for i in fpl_ids)
            out.append(f"| {_sofa_label(sofa[sofa_id])} | {claimants} |")
    else:
        out.append("None.")
    out.append("")

    low = sorted(
        (r for r in rows if not r.is_override and r.match_confidence < LOW_CONFIDENCE),
        key=lambda r: (r.match_confidence, r.fpl_id),
    )
    out += [f"## Low confidence (below {LOW_CONFIDENCE})", ""]
    if low:
        out += ["| FPL player | Sofascore player | Method | Confidence |", "|---|---|---|---|"]
        for r in low:
            out.append(
                f"| {_fpl_label(players[r.fpl_id])} | {_sofa_label(sofa[r.sofascore_id])} "
                f"| `{r.match_method}` | {r.match_confidence:.2f} |"
            )
    else:
        out.append("None.")
    out.append("")

    unmatched = sorted(
        (players[i] for i in result.unmatched), key=lambda p: (-p.minutes, p.club_id, p.id)
    )
    active = [p for p in unmatched if p.minutes > 0]
    inactive = [p for p in unmatched if p.minutes == 0]
    out += [f"## Unmatched active players ({len(active)})", ""]
    out += _unmatched_table(active, result) if active else ["None."]
    out += ["", f"## Unmatched inactive players ({len(inactive)})", ""]
    if inactive:
        out += [
            "No minutes yet (injured, fringe or youth players), mostly missing from "
            "Sofascore's squad lists. Matched once they appear in a squad list or a match.",
            "",
            "<details><summary>List</summary>",
            "",
            *_unmatched_table(inactive, result),
            "",
            "</details>",
        ]
    else:
        out.append("None.")
    out.append("")

    mapped_sofa = {r.sofascore_id for r in rows}
    played = set(session.scalars(select(PlayerMatchPosition.sofascore_player_id).distinct()))
    orphans = sorted((sofa[i] for i in played - mapped_sofa), key=lambda s: s.name)
    out += [f"## Sofascore players with positions but no FPL player ({len(orphans)})", ""]
    if orphans:
        out += [
            "Either FPL does not list them, or their name did not match an FPL "
            "player of the club (fix with an override). Their dots are never drawn.",
            "",
            "| Sofascore player | Team ID |",
            "|---|---|",
        ]
        out += [f"| {_sofa_label(s)} | {s.sofascore_team_id} |" for s in orphans]
    else:
        out.append("None.")
    out.append("")
    return "\n".join(out)


OVERRIDE_FORMAT = [
    "## Override file",
    "",
    f"`backend/data/{OVERRIDES_PATH.name}` (committed) fixes what auto-matching "
    "gets wrong or misses. It is applied on every mapping run (and every sync) "
    "and always wins.",
    "",
    "```csv",
    "fpl_id,sofascore_id,comment",
    "639,1464641,nickname: Chema Andrés on Sofascore",
    "123,,force no match: wrong person auto-matched",
    "```",
    "",
    "- `fpl_id`: FPL element ID (`fpl_players.id`, also the `FPL n` in this report).",
    "- `sofascore_id`: Sofascore player ID (the `Sofascore n` in this report, or "
    "the number at the end of the player's sofascore.com URL). The player is "
    "mapped to it with `match_method = override`, `is_override = true`. "
    "**Empty = force no match**: the player gets no row and is not auto-matched.",
    "- `comment`: free text, why the override exists. Quote it if it contains a comma.",
    "- One row per FPL player and per Sofascore player; a malformed file stops "
    "the run before anything is written. Deleting a row hands the player back "
    "to auto-matching on the next run.",
    "- A row is skipped (listed below) if its FPL player is unknown, or if its "
    "Sofascore player is not in the database yet; the player then stays unmatched "
    "until the next sync stores that Sofascore player.",
]


def _overrides_section(result: MappingResult, players: dict, sofa: dict) -> list[str]:
    applied, forced, skipped = (
        result.overrides_applied,
        result.forced_no_match,
        result.overrides_skipped,
    )
    out = [
        "## Overrides",
        "",
        f"Overrides applied: **{len(applied)}** · forced no match: **{len(forced)}** "
        f"· skipped: **{len(skipped)}**.",
        "",
    ]
    if applied or forced:
        out += ["| FPL player | Sofascore player | Comment |", "|---|---|---|"]
        for o in applied:
            out.append(
                f"| {_fpl_label(players[o.fpl_id])} | {_sofa_label(sofa[o.sofascore_id])} "
                f"| {_cell(o.comment)} |"
            )
        for o in forced:
            out.append(f"| {_fpl_label(players[o.fpl_id])} | no match (forced) | {_cell(o.comment)} |")
        out.append("")
    if skipped:
        out += ["Skipped:", "", "| FPL ID | Sofascore ID | Reason |", "|---|---|---|"]
        for o, why in skipped:
            out.append(f"| {o.fpl_id} | {o.sofascore_id if o.sofascore_id is not None else ''} | {why} |")
        out.append("")
    return out


def summary_lines(session: Session, result: MappingResult) -> list[str]:
    """A few lines for the mapping and sync CLIs."""
    cov = coverage(session)
    methods = ", ".join(f"{m}: {n}" for m, n in sorted(result.by_method.items()))
    lines = [
        f"  Player mapping: {len(result.matches)} auto ({methods or 'none'}), "
        f"{len(result.overrides_applied)} overrides, {len(result.forced_no_match)} forced "
        f"no match; rows added {result.added}, "
        f"changed {result.changed}, removed {result.removed}",
        f"    coverage: {cov.matched_pct:.1f}% of all FPL players, "
        f"{cov.active_pct:.1f}% of active ({cov.active_matched}/{cov.active})",
    ]
    for sofa_id, fpl_ids in result.clashes:
        lines.append(f"    clash: Sofascore {sofa_id} claimed by FPL {', '.join(map(str, fpl_ids))}")
    for o, why in result.overrides_skipped:
        lines.append(f"    override skipped: FPL {o.fpl_id}: {why}")
    return lines


def write_report(text: str, path: Path = REPORT_PATH) -> Path:
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


def _unmatched_table(players: list[FplPlayer], result: MappingResult) -> list[str]:
    lines = ["| FPL player | Role | Minutes | Reason |", "|---|---|---|---|"]
    for p in players:
        lines.append(f"| {_fpl_label(p)} | {p.role} | {p.minutes} | {result.unmatched[p.id]} |")
    return lines


def _fpl_label(p: FplPlayer) -> str:
    return f"{p.first_name} {p.second_name} ({p.web_name}, {p.club.short_name}, FPL {p.id})"


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _sofa_label(s: SofascorePlayer) -> str:
    return f"{s.name} (Sofascore {s.id})"


def _pct(part: int, whole: int) -> float:
    return 100 * part / whole if whole else 0.0
